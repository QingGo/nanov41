"""Invariants for the V4.1-Flash-aligned nano configs (docs/v41-aligned-spec.md).

Two layers of checks:
1. the committed `docs/aligned/d12_aligned.json` (generated by tools/make_aligned_config.py)
   must satisfy the alignment invariants without rebuilding the model;
2. a small freshly-generated config (d8-ish, fast) must reproduce the same invariants and the
   muP learning-rate rule end-to-end through the generator (which builds the model and counts
   parameters).
"""
from __future__ import annotations

import importlib.util
import json
import math
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
GEN = ROOT / "tools" / "make_aligned_config.py"
COMMITTED = ROOT / "docs" / "aligned" / "d12_aligned.json"

OFFICIAL_DIM = 5120
OFFICIAL_LR = 2.6e-4
OFFICIAL_ACTIVATION = 6 / 384  # 1.5625%


def _load_generator():
    spec = importlib.util.spec_from_file_location("make_aligned_config", GEN)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _check_report(report: dict) -> None:
    scale = report["scale"]
    acct = report["accounting"]
    engram = report["engram"]

    # 1) MoE activation fraction must match the official 6/384
    assert abs(acct["activation_fraction"] - OFFICIAL_ACTIVATION) < 1e-12, acct["activation_fraction"]
    assert acct["activation_fraction"] == report["engine_config"]["n_activated_experts"] / \
        report["engine_config"]["n_routed_experts"]

    # 2) layer modes / compression pattern line up with the layer count
    assert len(report["layer_modes"]) == scale["layers"]
    swa = report["layer_modes"].count("swa")
    assert swa == max(1, round(0.05 * scale["layers"]))
    assert "full" in report["layer_modes"] and "reuse" in report["layer_modes"]
    assert len(report["engine_config"]["compress_ratios"]) == scale["layers"]

    # 3) Engram geometry: params = rows * head_dim and ratio vs non-embedding backbone
    assert len(engram["engram_num_embeddings"]) == len(engram["engram_layer_ids"])
    assert acct["engram_params"] == sum(engram["engram_num_embeddings"]) * engram["engram_head_dim"]
    assert 0.33 <= acct["engram_nonembed_ratio"] <= 0.38, acct["engram_nonembed_ratio"]

    # 4) muP LR rule: eta * sqrt(dim_official / dim)
    expected_lr = OFFICIAL_LR * math.sqrt(OFFICIAL_DIM / scale["dim"])
    assert abs(report["optimizer"]["muon"]["lr"] - expected_lr) < 1e-12
    assert abs(report["optimizer"]["sinkhorn"]["engram_lr"] - 5.0 * expected_lr) < 1e-12
    assert report["optimizer"]["sinkhorn"]["gamma"] == 0.18
    assert report["optimizer"]["sinkhorn"]["K"] == 11
    assert report["optimizer"]["muon"]["update_rms_rescale"] == 0.18

    # 5) sequence length + precision scope per spec
    assert report["engine_config"]["max_seq_len"] == scale["seq_len"] == 8192
    assert report["precision"]["pretrain"]["linear"] == "fp8"
    assert report["precision"]["post_training"]["main_kv"] == "fp4_mxfp4_qat"
    assert report["misc"]["mtp"] == "omitted (V4.1)"
    assert report["misc"]["dspark"] == "post_pretrain_stage"


def test_committed_d12_aligned():
    report = json.loads(COMMITTED.read_text())
    _check_report(report)
    acct = report["accounting"]
    # sanity on the absolute scale chosen for d12 (dim 512, 12 layers, 128 experts top-2)
    assert 700e6 <= acct["backbone_params"] <= 850e6, acct["backbone_params"]
    assert 80e6 <= acct["active_params"] <= 110e6, acct["active_params"]


def test_generator_small_scale(tmp_path):
    out = tmp_path / "d8_aligned.json"
    subprocess.run([sys.executable, str(GEN), "--dim", "256", "--layers", "8",
                    "--seq", "8192", "--out", str(out)],
                   check=True, capture_output=True, text=True)
    report = json.loads(out.read_text())
    _check_report(report)
    assert report["scale"]["dim"] == 256 and report["scale"]["layers"] == 8


def test_helpers():
    mod = _load_generator()
    # activation-fraction helper (kept for ablations, not for the 128/2 default)
    topk, experts = mod._norm_uniform(1 / 64, max_den=128)
    assert abs(topk / experts - 1 / 64) < 1e-12

    modes = mod._layer_modes(12)
    assert len(modes) == 12
    assert modes[0] == "swa"
    # encoder: one full then reuse; decoder: full/reindex + reuse
    assert modes.count("full") == 2 and modes.count("reindex") == 1

    geo = mod.make_engram_geometry(100e6, 0.355, layers=[1, 2], max_ngram=4, n_heads=8,
                                   head_dim=32)
    assert 0.33 <= geo["achieved_ratio"] <= 0.38
    rows = sum(geo["engram_num_embeddings"])
    assert geo["engram_params"] == rows * 32
    assert len(geo["engram_num_embeddings"]) == 2
